import { contextBridge, ipcRenderer } from 'electron';

contextBridge.exposeInMainWorld('launcher', {
  discoverInstallation: () => ipcRenderer.invoke('discover-installation'),
  selectInstallation: () => ipcRenderer.invoke('select-installation'),
  installDestination: (pick: boolean) => ipcRenderer.invoke('install-destination', pick),
  installDump: (pick: boolean) => ipcRenderer.invoke('install-dump', pick),
  searchInstallDump: () => ipcRenderer.invoke('search-install-dump'),
  install: () => ipcRenderer.invoke('install'),
  rebuild: () => ipcRenderer.invoke('rebuild'),
  recoverBuild: (action: string) => ipcRenderer.invoke('recover-build', action),
  onRecoveryChanged: (callback: (result: unknown) => void) => ipcRenderer.on('recovery-changed', (_event, result) => callback(result)),
  setFirstRunPreference: (key: string, value: string | boolean) => ipcRenderer.invoke('first-run-preference', key, value),
  setHideWhilePlaying: (value: boolean) => ipcRenderer.invoke('set-hide-while-playing', value),
  savesInfo: () => ipcRenderer.invoke('saves-info'),
  chooseSaveExport: () => ipcRenderer.invoke('choose-save-export'),
  setSaveReport: (value: boolean) => ipcRenderer.invoke('set-save-report', value),
  exportSave: () => ipcRenderer.invoke('export-save'),
  importSave: (source: string) => ipcRenderer.invoke('import-save', source),
  openSavesDir: () => ipcRenderer.invoke('open-saves-dir'),
  modsList: (page: number) => ipcRenderer.invoke('mods-list', page),
  modAdd: (kind: string) => ipcRenderer.invoke('mod-add', kind),
  modEnabled: (name: string, value: boolean) => ipcRenderer.invoke('mod-enabled', name, value),
  modMove: (name: string, direction: number) => ipcRenderer.invoke('mod-move', name, direction),
  openModsDir: () => ipcRenderer.invoke('open-mods-dir'),
  controllerUsed: () => ipcRenderer.send('controller-used'),
  appearanceInfo: () => ipcRenderer.invoke('appearance-info'),
  appearancePreference: (key: string, value: string | number | boolean) => ipcRenderer.invoke('appearance-preference', key, value),
  appearanceAssets: () => ipcRenderer.invoke('appearance-assets'),
  appearanceImage: () => ipcRenderer.invoke('appearance-image'),
  appearanceBackground: (choose: boolean) => ipcRenderer.invoke('appearance-background', choose),
  steamInfo: () => ipcRenderer.invoke('steam-info'),
  steamAdd: () => ipcRenderer.invoke('steam-add'),
  settingsInfo: () => ipcRenderer.invoke('settings-info'),
  settingsPreference: (key: string, value: boolean | string) => ipcRenderer.invoke('settings-preference', key, value),
  settingsDump: () => ipcRenderer.invoke('settings-dump'),
  settingsOpen: (target: string) => ipcRenderer.invoke('settings-open', target),
  reportsHome: (after: string) => ipcRenderer.invoke('reports-home', after),
  reportsStatus: () => ipcRenderer.invoke('reports-status'),
  reportsTouch: () => ipcRenderer.invoke('reports-touch'),
  reportsAnswer: (answer: string) => ipcRenderer.invoke('reports-answer', answer),
  reportsConsent: (value: boolean) => ipcRenderer.invoke('reports-consent', value),
  reportsPreview: () => ipcRenderer.invoke('reports-preview'),
  reportsCrashOpen: () => ipcRenderer.invoke('reports-crash-open'),
  reportsCrashPreview: () => ipcRenderer.invoke('reports-crash-preview'),
  reportsCrashPreference: (value: boolean) => ipcRenderer.invoke('reports-crash-preference', value),
  reportsCrashAnswer: (answer: string) => ipcRenderer.invoke('reports-crash-answer', answer),
  reportsComment: (text: string, attach: boolean) => ipcRenderer.invoke('reports-comment', text, attach),
  checkUpdates: () => ipcRenderer.invoke('check-updates'),
  onUpdateChecked: (callback: (result: unknown) => void) => ipcRenderer.on('update-checked', (_event, result) => callback(result)),
  play: () => ipcRenderer.invoke('play'),
  cancelJob: () => ipcRenderer.invoke('cancel-job'),
  onBuildEnded: (callback: (result: unknown) => void) => ipcRenderer.on('build-ended', (_event, result) => callback(result)),
  onJobStatus: (callback: (result: unknown) => void) => ipcRenderer.on('job-status', (_event, result) => callback(result)),
  onGameWindowReady: (callback: () => void) => ipcRenderer.on('game-window-ready', () => callback()),
  onPlayEnded: (callback: (result: unknown) => void) => ipcRenderer.on('play-ended', (_event, result) => callback(result)),
  playMessageShown: (id: number, kind: string) => ipcRenderer.send('play-message-shown', id, kind),
});
